export function upgradeOffers(game) {
  const pool = UPGRADES.filter((u) => (game.upgrades[u.id] || 0) < u.max);
  const offset = (game.wave * 2 + game.chapter * 3) % pool.length;
  return Array.from(
    { length: Math.min(3, pool.length) },
    (_, i) => pool[(offset + i) % pool.length].id,
  );
}
